frutas =["Banana", "Maçã", "Pera", "laranja", "Fresa"]
print(frutas[0])  # Acessa o primeiro elemento da lista
print(frutas[2])  # Acessa o terceiro elemento da lista
print(frutas[-1])  # Acessa o último elemento da lista
print(frutas[1:4])  # Acessa os elementos do índice 1 ao 3 (exclusivo)
print(frutas[:3])  # Acessa os elementos do início até o índice 2 (exclusivo)
print(frutas[2:])  # Acessa os elementos do índice 2 até o final da lista
print(frutas[-3:])  # Acessa os últimos três elementos da lista
print(frutas[::2])  # Acessa os elementos da lista com um passo de 2
print(frutas[::-1])  # Acessa os elementos da lista em ordem reversa
frutas[0] = "Abacaxi"  # Modifica o primeiro elemento da lista
print(frutas)  # Imprime a lista modificada 
print(len(frutas))  # Imprime o tamanho da lista
print("Maçã" in frutas)  # Verifica se "Maçã" está na lista
print("Uva" not in frutas)  # Verifica se "Uva" não está na lista
