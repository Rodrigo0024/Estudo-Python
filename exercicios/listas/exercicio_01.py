#Crie uma lista com 5 elementos e imprima cada elemento usando um loop for
minha_lista = ["maça", "banana", "laranja", "uva", "pera"]
for fruta in minha_lista:
    print(fruta)  # Imprime cada elemento da lista

#acesse os ter ultimos 3 elementos da lista usando slicing
ultimos_tres = minha_lista[-3:]  # Acessa os últimos três elementos
print(ultimos_tres)  # Imprime os últimos três elementos